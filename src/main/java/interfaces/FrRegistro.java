    public void cargarTabla() {
    javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();
    modelo.setRowCount(0); 

    basedatos.JugadorDAO dao = new basedatos.JugadorDAO();
    java.util.ArrayList<clases.Jugador> lista = dao.consultarTodo();
    
    // Consulta los registros mediante la capa DAO y llena el JTable en la vista
    for (clases.Jugador j : lista) {
        Object[] fila = {
            j.getId(),
            j.getNombre(),
            j.getApellido(),
            j.getUser(),
            j.getPass(),
            j.isActivo() ? "Sí" : "No",
            j.getScore()
            
        };
        modelo.addRow(fila);
    }
}

