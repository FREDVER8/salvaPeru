    // Algoritmo de generación dinámica de credenciales
    private String generarContrasena(String nombre, String apellido) {
        // 1. Primeras 2 letras del nombre en minúscula
        String parteNombre = nombre.substring(0, 2).toLowerCase();
        
        // 2. Tres números aleatorios (entre 100 y 999)
        int numeros = (int)(Math.random() * 900) + 100;
        
        // 3. Primera letra del apellido en mayúscula
        String primeraApellido = apellido.substring(0, 1).toUpperCase();
        
        // 4. Última letra del apellido en minúscula
        String ultimaApellido = apellido.substring(apellido.length() - 1).toLowerCase();
        
        // 5. Un signo especial al azar de un arreglo de opciones
        char[] simbolos = {'#', '?', '$', '!', '+', '*'};
        int indiceAzar = (int)(Math.random() * simbolos.length);
        char signo = simbolos[indiceAzar];
        
        // Retorna la contraseña construida
        return parteNombre + numeros + primeraApellido + ultimaApellido + signo;
    }
