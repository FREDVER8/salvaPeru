// Procesa el registro de un nuevo jugador en la base de datos
    private void btnRegistrarseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarseActionPerformed
// Extrae el texto de las cajas eliminando espacios accidentales
String nombre = txtNombre.getText().trim();
String apellido = txtApellido.getText().trim();
String user = txtUsuario.getText().trim();

// Valida que no existan campos vacíos
if (nombre.isEmpty() || apellido.isEmpty() || user.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Por favor, llena todos los campos.");
    return;
}

// Valida la longitud mínima requerida para los nombres
if (nombre.length() < 2 || apellido.length() < 1) {
    JOptionPane.showMessageDialog(this, "El nombre debe tener al menos 2 letras y el apellido al menos 1.");
    return;
}

// Verifica en base de datos la disponibilidad del nombre de usuario
basedatos.JugadorDAO dao = new basedatos.JugadorDAO();
if (dao.existeUsuario(user)) {
    JOptionPane.showMessageDialog(this, "El nombre de usuario '" + user + "' ya existe. Por favor elige otro.");
    return;
}


// 1. Genera automáticamente la contraseña mediante la regla de negocio
String passGenerada = generarContrasena(nombre, apellido);

// 2. Crea el objeto entidad e inserta el registro mediante el DAO
clases.Jugador nuevoJugador = new clases.Jugador(nombre, apellido, user, passGenerada, true);
dao.altaJugador(nuevoJugador);

// 3. Genera el resumen para notificar al usuario sus credenciales de acceso
String mensajeResumen = "=== REGISTRO EXITOSO ===\n\n"
        + "• Nombre: " + nombre + " " + apellido + "\n"
        + "• Usuario: " + user + "\n"
        + "• Contraseña Generada: " + passGenerada + "\n"
        + "• Estado: Activo\n\n"
        + "¡Guarda tu contraseña para ingresar en el Login!";

JOptionPane.showMessageDialog(this, mensajeResumen, "Datos del Jugador", JOptionPane.INFORMATION_MESSAGE);

// 4. Actualiza el control JTable en pantalla (si aplica)
cargarTabla();

// 5. Limpia las cajas de texto para un nuevo registro
txtNombre.setText("");
txtApellido.setText("");
txtUsuario.setText("");
    }//GEN-LAST:event_btnRegistrarseActionPerformed

