    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
    // Obtiene los datos de las cajas de texto eliminando espacios vacíos al inicio y al final
    String user = txtUser.getText().trim();
    String pass = txtContra.getText().trim();

    // Valida que el usuario no haya dejado ningún campo en blanco
    if (user.isEmpty() || pass.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingrese usuario o contraseña, no dejar en blanco por favor.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
        return; // Interrumpe la ejecución si los datos están incompletos
    }

    // Instancia el objeto DAO para comunicarse con la base de datos
    basedatos.JugadorDAO dao = new basedatos.JugadorDAO();
boolean valido = dao.validarLogin(user, pass);

if (valido) {
    // 1. Guardamos el usuario en la variable estática para que no se pierda
    usuarioLogueado = user; 

    JOptionPane.showMessageDialog(this, "¡OLAAAAA!, " + user, "Atención", JOptionPane.INFORMATION_MESSAGE);
    
    // 2. Abrimos el juego normal
    FrJuego juego = new FrJuego();
    juego.setLocationRelativeTo(null);
    juego.setVisible(true);

    this.dispose(); 
} else {
    JOptionPane.showMessageDialog(this, "El usuario o contraseña que escribiste es incorrecto.", "Error de Autenticación", JOptionPane.ERROR_MESSAGE);
}
}
    

